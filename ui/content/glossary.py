def lookup(word):
    w = word.lower()
    for e in entries():
        if e["term"].lower() == w or w in [p.strip().lower() for p in e["term"].split("/")]:
            return e["simple"]
    return ""


def search(query):
    q = (query or "").strip().lower()
    if not q:
        return entries()
    return [e for e in entries() if any(q in e[k].lower() for k in ("term", "simple", "why", "example", "deeper"))]
